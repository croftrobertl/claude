    /** The sticker colour for a section key. */
    public static function color_for(string $section_key): string
    {
        $key = strtolower(trim($section_key));
        return self::SECTION_COLORS[$key] ?? self::COLOR_FALLBACK;
    }

    /** The glyph key inside an Elementor icon array, or '' if it is not ours. */
    public static function key_of($icon): string
    {
        if (!is_array($icon) || (string) ($icon['library'] ?? '') !== self::LIBRARY) { return ''; }
        $value = (string) ($icon['value'] ?? '');
        if (strpos($value, self::PREFIX) !== 0) { return ''; }
        $key = substr($value, strlen(self::PREFIX));
        return isset(self::glyphs()[$key]) ? $key : '';
    }

    /** True when this icon belongs to our library (whether or not it resolves). */
    public static function is_ours($icon): bool
    {
        return is_array($icon) && (string) ($icon['library'] ?? '') === self::LIBRARY;
    }

    /**
     * Echo one glyph as an <svg><use></svg> and record it for the sprite.
     *
     * An unknown value from our own library prints NOTHING — not an empty
     * <svg>, not a broken <use> pointing at a symbol that will never exist, and
     * nothing to the console. A guide can therefore carry a value this build
     * does not know without the page showing damage.
     */
    public static function render($icon, array $attrs = []): void
    {
        $key = self::key_of($icon);
        if ($key === '') { return; }
        self::$used[$key] = true;
        $g = self::glyphs()[$key];
        $class = 'dccgg-glyph dccgg-glyph--' . $key;
        if (!empty($attrs['class'])) { $class .= ' ' . $attrs['class']; }
        $style = '';
        if ((float) $g['scale'] !== 1.0) {
            // Per-glyph optical scale: the Material washer is drawn on another
            // grid and needs trimming to sit level with the Phosphor seven.
            $style = ' style="--dccgg-glyph-scale:' . esc_attr((string) $g['scale']) . '"';
        }
        printf(
            '<svg class="%s" viewBox="%s" aria-hidden="true" focusable="false"%s><use href="#%s"></use></svg>',
            esc_attr($class),
            esc_attr(self::outer_view_box($g['viewBox'])),
            $style, // phpcs:ignore WordPress.Security.EscapeOutput — built from esc_attr above
            esc_attr(self::symbol_id($key))
        );
    }

    /**
     * The viewBox for the <svg> that HOLDS the <use> — always at the origin.
     *
     * A <symbol> carries its own viewBox, and that is what maps its content
     * into the <use> box: the result always lands at 0,0. So the wrapper must
     * start at 0,0 too, whatever the glyph's native origin. Material Symbols
     * are drawn on "0 -960 960 960"; copying that onto the wrapper pushed the
     * washer a whole viewport below the visible area and the sticker rendered
     * empty. Phosphor's "0 0 256 256" hid the bug, because for those two the
     * origin already agrees.
     */
    public static function outer_view_box(string $view_box): string
    {
        $parts = preg_split('/[\s,]+/', trim($view_box));
        if (!is_array($parts) || count($parts) !== 4) { return $view_box; }
        return '0 0 ' . $parts[2] . ' ' . $parts[3];
    }

    /** The in-page id a <use> points at. */
    public static function symbol_id(string $key): string
    {
        return 'dccgg-sym-' . $key;
    }

    /** Test seam: forget what this request has used. */
    public static function reset(): void { self::$used = []; }

    /** Which glyphs this request actually rendered. */
    public static function used(): array { return array_keys(self::$used); }

    /**
     * Echo the sprite: one <symbol> per glyph ACTUALLY used, and nothing at all
     * when none were. Printed after the tiles rather than before them, because
     * the set is only known once they have rendered; <use> resolves by id once
     * the document has parsed, so order does not matter. It is also why the
     * sprite lives in the page rather than in the stage, which gets moved to
     * <body> when a section opens — the references stay in the same document
     * either way.
     */
    public static function sprite(): void
    {
        if (!self::$used) { return; }
        $glyphs = self::glyphs();
        echo '<svg class="dccgg-sprite" aria-hidden="true" focusable="false" style="position:absolute;width:0;height:0;overflow:hidden" xmlns="http://www.w3.org/2000/svg">';
        foreach (array_keys(self::$used) as $key) {
            $g = $glyphs[$key];
            printf(
                '<symbol id="%s" viewBox="%s">%s</symbol>',
                esc_attr(self::symbol_id($key)),
                esc_attr($g['viewBox']),
                $g['body'] // phpcs:ignore WordPress.Security.EscapeOutput — plugin-bundled path data, not input
            );
        }
        echo '</svg>';
    }

    /**
     * Register the library with Elementor's Icons control so the eight glyphs
     * can be picked in the editor. The picker draws each one from
     * assets/css/dccgg-icons.css, which masks a data: URI per class — no
     * webfont, and nothing fetched from outside the site.
     */
    public static function register_tab(array $tabs): array
    {
        $tabs[self::LIBRARY] = [
            'name'          => self::LIBRARY,
            'label'         => __('DCC Guide', 'dcc-guest-guide'),
            'labelIcon'     => 'dccgg-ico dccgg-icon-devices',
            'prefix'        => self::PREFIX,
            'displayPrefix' => 'dccgg-ico',
            'url'           => DCCGG_URL . 'assets/css/dccgg-icons.css',
            'enqueue'       => [],
            'ver'           => DCCGG_VERSION,
            'fetchJson'     => DCCGG_URL . 'assets/icons/dccgg-icons.json',
            'native'        => false,
        ];
        return $tabs;
    }
