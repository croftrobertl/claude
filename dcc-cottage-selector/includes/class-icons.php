    /**
     * Decorative inline SVG for a Font Awesome value, or '' when this class does not
     * carry it. Height 1em; the width follows the glyph's own proportions, as the
     * font glyph's advance width does.
     */
    public static function svg(string $value): string
    {
        $value = trim($value);
        if (!isset(self::SVG[$value])) {
            return '';
        }
        [$w, $h, $d] = self::SVG[$value];
        // The box is stated ON the element too (0.58.0), in em, from the glyph's own
        // proportions: an <svg> with only a viewBox is 300x150 until a stylesheet sizes
        // it, so its space is now reserved whatever arrives first. The CSS (1em tall,
        // width auto) computes the same box.
        return '<svg class="dccs-svg-icon" aria-hidden="true" focusable="false" xmlns="http://www.w3.org/2000/svg" width="'
            . rtrim(rtrim(number_format($w / $h, 4, '.', ''), '0'), '.') . 'em" height="1em" viewBox="0 0 '
            . (int) $w . ' ' . (int) $h . '"><path fill="currentColor" d="' . $d . '"/></svg>';
    }
