'use strict';
/**
 * DCC Seasons — write the Anniversary's art pack (4.13.5),
 * dcc-seasons/assets/js/art-anniversary.js: Rob's picks (2026-10-29) from
 * the sheets, drawn by the SAME sources the sheets were (tools/anniv-
 * pieces.js, tools/anniv-percent.js), so what ships is what he chose:
 *   1 hearts A, blush · 2 gold rings B, two bands linked · 3 crystal A, the
 *   cut drop · 4 the toast A, flutes clinking · 5 the date A, the gold band
 *   (11·11·11) · 6 the year count A, a crystal numeral of its own ·
 *   11 the percentages A, gold numerals alone.
 * The year count and the two percentages are COMPUTED on the visitor's
 * day (or the check link's forced date, CFG.date), never typed: years since
 * 11 Nov 2011, and those years as a share of each birth's age (26 Mar 1989,
 * 25 Mar 1986) in days of 365.2425, rounded to the nearest whole number
 * (Rob). No names anywhere: the figures float, nothing says whose they are.
 * The crane is its own pack (tools/crane-build.js), shared with Florida Keys.
 *
 *   node tools/anniv-build.js          (writes the pack)
 *   node tools/anniv-build.js --check  (exits 1 if the pack is stale)
 */
const fs = require('fs');
const path = require('path');
const { P } = require('./anniv-pieces');
const OUT = path.join(__dirname, '..', 'dcc-seasons', 'assets', 'js', 'art-anniversary.js');

const one = s => s.replace(/\n/g, '');
const body = s => one(s.slice(s.indexOf('|') + 1));
/* the gold the percentages were drawn with (tools/anniv-percent.js GOLD) */
const GOLDP = id => `<linearGradient id="${id}" x2="0" y2="1"><stop stop-color="#7C5C16"/><stop offset=".22" stop-color="#C9A227"/><stop offset=".42" stop-color="#F6E3A0"/><stop offset=".55" stop-color="#E2C25A"/><stop offset=".8" stop-color="#A9831F"/><stop offset="1" stop-color="#6E5013"/></linearGradient>`;
const pctA = id => `'34 20|<defs>${GOLDP(id)}</defs><text x="17" y="16" font-family="Georgia,serif" font-size="16" font-weight="700" fill="#5A410C" text-anchor="middle" stroke="#5A410C" stroke-width="1.6" stroke-linejoin="round">' + t + '</text><text x="17" y="15.4" font-family="Georgia,serif" font-size="16" font-weight="700" fill="url(#${id})" text-anchor="middle">' + t + '</text>'`;
/* the lab's look A, checked: the same markup with the figure spliced in */
const lab = fs.readFileSync(path.join(__dirname, 'anniv-percent.js'), 'utf8');
if (!lab.includes('font-size="16" font-weight="700" fill="#5A410C" text-anchor="middle" stroke="#5A410C" stroke-width="1.6" stroke-linejoin="round">${t}</text><text x="17" y="15.4" font-family="Georgia,serif" font-size="16" font-weight="700" fill="url(#${id}a)"')) {
  throw new Error('tools/anniv-percent.js look A changed: update anniv-build.js to match it');
}
const yearA = body(P.crystalA).replace(/dccAnC1/g, 'dccAnY1');

const src = `/* DCC Seasons — the Anniversary's art (4.13.5): Rob's picks from the
 * 2026-10-29 sheets, falling on 11 November. The loader fetches it only
 * that day (or in a preview), with the crane's pack, before the engine.
 *
 * GENERATED by tools/anniv-build.js from tools/anniv-pieces.js and
 * tools/anniv-percent.js. Do not edit here: edit those and regenerate. */
(function (W) {
	'use strict';
	/* the day the figures are worked out for: the check link's forced date
	 * (CFG.date, key-gated server-side), else the visitor's own */
	function day() {
		var f = W.DCC_SEASONS && W.DCC_SEASONS.date, p = f ? String(f).split('-') : null, n = new Date();
		return p ? Date.UTC(+p[0], +p[1] - 1, +p[2]) : Date.UTC(n.getFullYear(), n.getMonth(), n.getDate());
	}
	var YR = 365.2425 * 864e5;
	/* years married this 11 Nov, and that as a share of each age, rounded */
	function figs() {
		var d = new Date(day()), y = d.getUTCFullYear(), on = Date.UTC(y, 10, 11), wed = (on - Date.UTC(2011, 10, 11)) / YR;
		return [y - 2011, Math.round(100 * wed / ((on - Date.UTC(1989, 2, 26)) / YR)), Math.round(100 * wed / ((on - Date.UTC(1986, 2, 25)) / YR))];
	}
	function pct(t, n) { t = t + '%'; return ${pctA("dccAnP' + n + '")}; }
	var S = {
		anheart: '${one(P.heartA)}',
		anrings: '${one(P.ringB)}',
		ancrystal: '${one(P.crystalA)}',
		antoast: '${one(P.toastA)}',
		andate: '${one(P.dateA)}',
		anyear: function () { return '20 28|${yearA}<text x="10" y="21" font-family="Georgia,serif" font-size="8.4" font-weight="700" fill="#2F5F7C" text-anchor="middle">' + figs()[0] + '</text>'; },
		anpct1: function () { return pct(figs()[1], 1); },
		anpct2: function () { return pct(figs()[2], 2); }
	};
	(W.DCCSeasonsArt = W.DCCSeasonsArt || {}).anniversary = { svgs: S, annivFigs: figs };
}(window));
`;
if (/'/.test([P.heartA, P.ringB, P.crystalA, P.toastA, P.dateA, yearA].join(''))) { throw new Error('a sprite contains a quote'); }
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== src) { console.error('art-anniversary.js is stale: run node tools/anniv-build.js'); process.exit(1); }
  console.log('art-anniversary.js is current');
} else {
  fs.writeFileSync(OUT, src);
  console.log(OUT, src.length, 'bytes');
}
