#!/usr/bin/env python3
"""
Regenerate the bundled icon glyphs.

Reads tools/icon-glyphs.json (extracted from the @phosphor-icons/core and
@material-symbols/svg-400 npm packages) and writes:
  dcc-guest-guide/includes/class-icons.php      the glyph data
  dcc-guest-guide/assets/icons/dccgg-icons.json  the list Elementor's picker fetches
  dcc-guest-guide/assets/css/dccgg-icons.css     the picker faces (editor only)

    python3 tools/build-icons.py
"""
import json, os, urllib.parse
G = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'icon-glyphs.json')))
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'dcc-guest-guide') + '/'
# The washer is drawn on Material's 960 grid and is a solid block, so at 1.00 it
# crowds the circle next to Phosphor's lighter shapes. 0.90 matches it by eye at
# both 60px and 34px; see the release notes.
SCALE = {'laundry': 0.90}
ORDER = ['devices', 'laundry', 'campfire', 'fish', 'suitcase-rolling', 'gavel', 'signpost', 'hand-heart']

rows = []
for k in ORDER:
    v = G[k]
    s = SCALE.get(k, 1.0)
    rows.append(
        "        '%s' => [\n"
        "            'label'   => '%s',\n"
        "            'viewBox' => '%s',\n"
        "            'scale'   => %s,\n"
        "            'source'  => '%s',\n"
        "            'body'    => '%s',\n"
        "        ]," % (k, v['label'], v['viewBox'], ('%.2f' % s), v['source'], v['body'].replace("\\", "\\\\").replace("'", "\\'")))
php = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'class-icons.php.tpl')).read()
php = php.replace('/*__GLYPHS__*/', '\n'.join(rows))
open(OUT + 'includes/class-icons.php', 'w').write(php)

# Elementor's picker fetches this list.
os.makedirs(OUT + 'assets/icons', exist_ok=True)
json.dump({'icons': ['dccgg-icon-' + k for k in ORDER]}, open(OUT + 'assets/icons/dccgg-icons.json', 'w'))

# ...and needs CSS to DRAW them in the picker. No webfont: each class masks a
# data: URI of its own glyph, so the picker shows the real shape and the plugin
# still makes no outside request.
css = ["/* DCC Guest Guide — icon picker faces (editor only, v0.24.1).",
       "   Generated by tools/build-icons.py from the bundled glyph data. Do not",
       "   hand-edit. The front end does NOT load this file: it uses the inline",
       "   <symbol> sprite instead. */",
       ".dccgg-ico{display:inline-block;width:1em;height:1em;background-color:currentColor;",
       " -webkit-mask-repeat:no-repeat;mask-repeat:no-repeat;-webkit-mask-position:center;mask-position:center;",
       " -webkit-mask-size:contain;mask-size:contain;vertical-align:-0.125em}"]
for k in ORDER:
    v = G[k]
    svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="%s">%s</svg>' % (v['viewBox'], v['body'])
    uri = urllib.parse.quote(svg, safe="/:=\"' <>?,()-.")
    css.append('.dccgg-icon-%s{-webkit-mask-image:url("data:image/svg+xml,%s");mask-image:url("data:image/svg+xml,%s")}' % (k, uri, uri))
open(OUT + 'assets/css/dccgg-icons.css', 'w').write('\n'.join(css) + '\n')
print('glyphs:', len(ORDER), '| picker css bytes:', os.path.getsize(OUT + 'assets/css/dccgg-icons.css'))
